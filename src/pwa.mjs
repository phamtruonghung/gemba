// src/pwa.mjs — the web manifest and the service worker, and the one rule about what the worker may keep.
//
// The worker is a progressive enhancement: every page works without it. Its job is small — keep the
// public reading surface (the shell pages and the notes) readable on a phone with no signal, and show an
// honest offline page otherwise. The rule that matters is what it must NEVER keep: anything that knows
// who you are, or that moves money or state. That rule is `cachePolicy`, a pure function whose source is
// embedded verbatim into sw.js, so the function the tests exercise is the function the browser runs.
//
// The worker cannot see Set-Cookie (a forbidden response header), so the server cooperates: every
// response that sets a cookie, belongs to a never-cache path, or is rendered for a signed-in person
// carries `cache-control: private, no-store` (see server.mjs), and the worker refuses to store those.

