/**
 * What may the worker do with this request? 'none' (never stored; the default, so anything unknown is
 * safe), 'network-first' (the JSON API: always the network, never stored), 'swr' (notes: stale while
 * revalidate), 'shell' (network first, the cached copy when offline).
 * Self-contained on purpose: it is serialised with toString() into sw.js. No outer references.
 */
export function cachePolicy(pathname, method) {
  if (String(method || 'GET').toUpperCase() !== 'GET') return 'none';
  var p = String(pathname);
  try {
    for (var i = 0; i < 3 && p.indexOf('%') >= 0; i++) p = decodeURIComponent(p);
  } catch (e) {
    return 'none';
  }
  if (/[%\0]/.test(p)) return 'none'; // still encoded after three decodes: not a path we understand
  p = p.replace(/\\/g, '/').toLowerCase();
  var out = [];
  p.split('/').forEach(function (s) {
    if (s === '' || s === '.') return;
    if (s === '..') out.pop();
    else out.push(s);
  });
  p = '/' + out.join('/');
  if (/^\/(desk|book)/.test(p)) return 'none';
  if (/^\/(account|admin|signin|signup|signout|invite|ask|c|q|b|qt|healthz)(\/|$)/.test(p)) return 'none';
  if (/^\/api(\/|$)/.test(p)) return 'network-first';
  if (/^\/notes\/[^\/]+$/.test(p)) return 'swr';
  if (['/', '/library', '/how-it-works', '/experts', '/offline', '/manifest.webmanifest', '/dieu-khoan', '/bao-mat', '/khieu-nai'].indexOf(p) >= 0) return 'shell';
  if (/^\/icons\/[^\/]+$/.test(p)) return 'shell';
  if (/^\/app\.[0-9a-f]{12}\.css$/.test(p)) return 'shell';
  return 'none';
}

/** A sign-out is a POST navigation; when the worker sees one it drops the runtime (notes) cache. */
export function purgesOnLogout(pathname, method) {
  if (String(method).toUpperCase() !== 'POST') return false;
  var p = String(pathname);
  try {
    for (var i = 0; i < 3 && p.indexOf('%') >= 0; i++) p = decodeURIComponent(p);
  } catch (e) {
    return true; // cannot read it: purge anyway, a purge is always safe
  }
  return /\/(signout|admin\/logout)\/*$/i.test(p.replace(/\\/g, '/'));
}

const SW_TEMPLATE = `// Gemba service worker (generated by src/pwa.mjs; version __VERSION__).
'use strict';
var VERSION = '__VERSION__';
var SHELL_CACHE = 'gemba-shell-' + VERSION;
var NOTES_CACHE = 'gemba-notes-' + VERSION;
var SHELL = __SHELL__;

__CACHE_POLICY__

__PURGES_ON_LOGOUT__

// Never keep a response that is not a plain, successful, same-origin, un-redirected 200, or that the
// server marked private / no-store (cookie-setting and signed-in responses are).
function storable(res) {
  if (!res || res.status !== 200 || !res.ok || res.type !== 'basic' || res.redirected) return false;
  var cc = (res.headers.get('cache-control') || '').toLowerCase();
  return cc.indexOf('no-store') < 0 && cc.indexOf('private') < 0;
}

function offline() {
  return caches.match('/offline', { cacheName: SHELL_CACHE }).then(function (hit) {
    return hit || new Response('You are offline.', { status: 503, headers: { 'content-type': 'text/plain; charset=utf-8' } });
  });
}

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(SHELL_CACHE).then(function (cache) {
      return Promise.all(SHELL.map(function (url) {
        // credentials: 'omit' so the precache holds the signed-out pages, never somebody's own.
        return fetch(url, { credentials: 'omit', cache: 'reload' }).then(function (res) {
          return storable(res) ? cache.put(url, res) : null;
        }).catch(function () { return null; });
      }));
    }).then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.filter(function (k) {
        return k.indexOf('gemba-') === 0 && k !== SHELL_CACHE && k !== NOTES_CACHE;
      }).map(function (k) { return caches.delete(k); }));
    }).then(function () { return self.clients.claim(); })
  );
});

self.addEventListener('fetch', function (event) {
  var req = event.request;
  var url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (purgesOnLogout(url.pathname, req.method)) {
    event.waitUntil(caches.delete(NOTES_CACHE));
    return; // the sign-out itself goes to the network untouched
  }
  if (req.method !== 'GET' || req.headers.has('range')) return;
  var policy = cachePolicy(url.pathname, req.method);
  var nav = req.mode === 'navigate';
  if (policy === 'network-first') return; // the API: straight to the network, never stored
  if (policy === 'none') {
    if (nav) event.respondWith(fetch(req).catch(offline)); // not stored; only the offline page on failure
    return;
  }
  if (policy === 'swr') {
    event.respondWith(caches.open(NOTES_CACHE).then(function (cache) {
      return cache.match(req).then(function (hit) {
        var net = fetch(req).then(function (res) {
          if (storable(res)) cache.put(req, res.clone());
          return res;
        });
        if (hit) { event.waitUntil(net.catch(function () {})); return hit; }
        return net.catch(function () { return nav ? offline() : Response.error(); });
      });
    }));
    return;
  }
  // 'shell': the network when there is one, the last good copy when there is not.
  event.respondWith(fetch(req).then(function (res) {
    if (storable(res)) {
      var copy = res.clone();
      event.waitUntil(caches.open(SHELL_CACHE).then(function (c) { return c.put(req, copy); }));
    }
    return res;
  }).catch(function () {
    return caches.match(req, { cacheName: SHELL_CACHE }).then(function (hit) {
      return hit || (nav ? offline() : Response.error());
    });
  }));
});
`;

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

/** The worker source and its version: a short hash of the template, the policy, the views and public/. */
export function buildServiceWorker({ publicDir = PUBLIC_DIR } = {}) {
  const h = createHash('sha256');
  h.update(SW_TEMPLATE).update(String(cachePolicy)).update(String(purgesOnLogout)).update(JSON.stringify(SHELL_URLS));
  h.update(readFileSync(join(HERE, 'views.mjs')));
  try { for (const f of walk(publicDir)) h.update(f.slice(publicDir.length)).update(readFileSync(f)); } catch { /* no public dir */ }
  const version = h.digest('hex').slice(0, 10);
  const source = SW_TEMPLATE
    .split('__VERSION__').join(version)
    .split('__SHELL__').join(JSON.stringify(SHELL_URLS))
    .split('__CACHE_POLICY__').join(String(cachePolicy))
    .split('__PURGES_ON_LOGOUT__').join(String(purgesOnLogout));
  return { source, version };
}
